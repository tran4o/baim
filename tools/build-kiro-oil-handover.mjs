import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
const root=process.cwd(),source=path.join(root,'assets_src/characters/mehana_waiter/oil-handover-web-c01');
const recipe=JSON.parse(await fs.readFile(path.join(source,'recipe.json'),'utf8'));
const dir='assets/chapter1/characters/mehana_waiter/oil-handover-web-c01';
await fs.mkdir(path.join(root,dir),{recursive:true});
const assets={kiroOilScale:`${dir}/scale.png`,kiroOilHandover:`${dir}/atlas.webp`},composite=[];
for(const [i,entry] of recipe.sourceFiles.entries()){
 const input=await fs.readFile(path.join(source,entry.file));
 if(createHash('sha256').update(input).digest('hex')!==entry.sha256)throw Error('Source hash mismatch: '+entry.file);
 composite.push({input:await sharp(input).resize(252,448).png().toBuffer(),left:i%8*252,top:Math.floor(i/8)*448});
}
await sharp({create:{width:2016,height:Math.ceil(recipe.sourceFiles.length/8)*448,channels:4,background:'#00000000'}}).composite(composite).webp({lossless:true}).toFile(path.join(root,dir,'atlas.webp'));
await fs.writeFile(path.join(root,'src/content/art/kiroOilHandover.generated.js'),
 '// Derived from owner-approved sources; generated by tools/build-kiro-oil-handover.mjs.\n'+
 'export const kiroOilAssets = '+JSON.stringify(assets,null,2)+';\n'+
 'export const kiroOilSequence = '+JSON.stringify({id:recipe.id,sceneId:recipe.sceneId,layerId:recipe.layerId,durationMs:recipe.durationMs,frames:recipe.frames},null,2)+';\n');
console.log('Built '+recipe.sourceFiles.length+' half-size lossless review frames; original sources preserved');
